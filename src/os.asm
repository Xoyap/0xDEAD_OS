[BITS 64]
default rel

global _e

%define ST_BS 96
%define BS_LP 0x140
%define GOP_M 24
%define M_INF 8
%define M_FB 24
%define M_FBS 32
%define I_HRES 4
%define I_VRES 8
%define I_SL 32

%define CHAR_W 9
%define CHAR_H 10

%define START_X 100
%define START_Y 100

%define CURSOR_W 8
%define CURSOR_H 10
%define CURSOR_DELAY 50000

section .text

;================ entry =================

_e:
    and rsp, -16
    sub rsp, 32

    mov r12, rdx

    mov rax, [r12 + 0x30]
    mov [conin], rax

    mov rbx, [r12 + ST_BS]
    mov rax, [rbx + BS_LP]

    ;================ gop =================

    lea rcx, [guid]
    xor edx, edx
    lea r8, [gop]

    call rax
    add rsp, 32

    test rax, rax
    jnz fail

    ;================ mode =================

    mov rbx, [gop]
    test rbx, rbx
    jz fail

    mov rbx, [rbx + GOP_M]
    test rbx, rbx
    jz fail

    mov rax, [rbx + M_FB]
    test rax, rax
    jz fail
    mov [fb], rax

    mov rsi, [rbx + M_INF]
    test rsi, rsi
    jz fail

    mov eax, [rsi + I_HRES]
    test eax, eax
    jnz .hres_ok
    mov eax, 1
.hres_ok:
    mov [screen_width], rax

    mov eax, [rsi + I_VRES]
    test eax, eax
    jnz .vres_ok
    mov eax, 1
.vres_ok:
    mov [screen_height], rax

    mov eax, [rsi + I_SL]
    test eax, eax
    jnz .stride_ok
    mov eax, [rsi + I_HRES]
    test eax, eax
    jnz .stride_ok
    mov eax, 1
.stride_ok:
    mov [sl], eax

    mov eax, [sl]
    cmp [screen_width], rax
    jbe .width_ok
    mov [screen_width], rax
.width_ok:

    ;================ clear =================

    mov rcx, [rbx + M_FBS]
    test rcx, rcx
    jnz .clear_ok

    mov eax, [sl]
    mov rcx, [screen_height]
    mul rcx
    mov rcx, rax
    jmp .clear_do

.clear_ok:
    shr rcx, 2

.clear_do:
    xor eax, eax
    mov rdi, [fb]
    cld
    rep stosd

    ;================ start =================

    mov qword [cursor_x], START_X
    mov qword [cursor_y], START_Y

    call ensure_y

    lea r9, [msg]
    call draw_text

    call init_keyboard

    call draw_cursor
    mov byte [cursor_state], 1
    mov qword [cursor_timer], CURSOR_DELAY

    ;================ main =================

.main_loop:
    call keyboard_poll
    test al, al
    jz .tick

    call erase_cursor_if_visible

    cmp al, 8
    je .do_backspace
    cmp al, 10
    je .do_newline

    mov r9b, al
    call console_putc
    jmp .show_cursor

.do_backspace:
    call backspace
    jmp .show_cursor

.do_newline:
    call newline

.show_cursor:
    call draw_cursor
    mov byte [cursor_state], 1
    mov qword [cursor_timer], CURSOR_DELAY

.tick:
    call cursor_tick
    jmp .main_loop

;================ text =================

draw_text:
    push rsi
    mov rsi, r9

.next:
    mov al, [rsi]
    test al, al
    jz .done

    cmp al, 10
    je .newline

    mov r9b, al
    call console_putc

    inc rsi
    jmp .next

.newline:
    call newline
    inc rsi
    jmp .next

.done:
    pop rsi
    ret

;================ putc =================

console_putc:
    push rax
    push rcx
    push rdx
    push r8
    push r12

    movzx r12d, r9b

    mov rax, [cursor_x]
    add rax, CHAR_W
    cmp rax, [screen_width]
    jbe .x_ok
    call newline
.x_ok:
    call ensure_y

    mov rcx, [cursor_x]
    mov rdx, [cursor_y]
    call erase_char

    mov rcx, [cursor_x]
    mov rdx, [cursor_y]
    mov r8d, 0x00FFFFFF
    mov r9b, r12b
    call draw_char

    add qword [cursor_x], CHAR_W

    mov rax, [cursor_x]
    cmp rax, [screen_width]
    jb .exit
    call newline

.exit:
    pop r12
    pop r8
    pop rdx
    pop rcx
    pop rax
    ret

;================ edit =================

backspace:
    cmp qword [cursor_x], START_X
    jle .done

    sub qword [cursor_x], CHAR_W

    mov rcx, [cursor_x]
    mov rdx, [cursor_y]
    call erase_char

.done:
    ret

newline:
    mov qword [cursor_x], START_X
    add qword [cursor_y], CHAR_H
    call ensure_y
    ret

;================ view =================

ensure_y:
    mov rax, [screen_height]
    cmp rax, CHAR_H
    jbe .zero

    mov rax, [cursor_y]
    add rax, CHAR_H
    cmp rax, [screen_height]
    jbe .done

    call scroll_up

    mov rax, [screen_height]
    sub rax, CHAR_H
    mov [cursor_y], rax
    ret

.zero:
    mov qword [cursor_y], 0

.done:
    ret

;================ scroll =================

scroll_up:
    push rsi
    push rdi
    push rcx
    push rax
    push rdx

    mov rdi, [fb]
    mov rax, [screen_height]
    cmp rax, CHAR_H
    jbe .done

    mov eax, [sl]
    mov ecx, CHAR_H
    mul rcx
    lea rsi, [rdi + rax * 4]

    mov eax, [sl]
    mov rcx, [screen_height]
    sub rcx, CHAR_H
    mul rcx
    mov rcx, rax
    cld
    rep movsd

    mov rdi, [fb]
    mov eax, [sl]
    mov rcx, [screen_height]
    sub rcx, CHAR_H
    mul rcx
    lea rdi, [rdi + rax * 4]

    mov eax, [sl]
    mov ecx, CHAR_H
    mul rcx
    mov rcx, rax
    xor eax, eax
    rep stosd

.done:
    pop rdx
    pop rax
    pop rcx
    pop rdi
    pop rsi
    ret

;================ cursor =================

draw_cursor:
    mov rdi, [fb]
    mov eax, [sl]
    mov rcx, [cursor_y]
    imul rcx, rax
    add rcx, [cursor_x]

    mov r8, CURSOR_H

.cy:
    push r8
    mov r9, CURSOR_W

.cx:
    mov dword [rdi + rcx * 4], 0x00FFFFFF
    inc rcx
    dec r9
    jnz .cx

    mov eax, [sl]
    add rcx, rax
    sub rcx, CURSOR_W

    pop r8
    dec r8
    jnz .cy

    ret

erase_cursor:
    mov rdi, [fb]
    mov eax, [sl]
    mov rcx, [cursor_y]
    imul rcx, rax
    add rcx, [cursor_x]

    mov r8, CURSOR_H

.ecy:
    mov r9, CURSOR_W

.ecx:
    mov dword [rdi + rcx * 4], 0
    inc rcx
    dec r9
    jnz .ecx

    mov eax, [sl]
    add rcx, rax
    sub rcx, CURSOR_W

    dec r8
    jnz .ecy

    ret

;================ cell =================

erase_char:
    push rbx

    mov rdi, [fb]
    mov ebx, [sl]

    mov r10, rdx
    imul r10, rbx
    add r10, rcx
    shl r10, 2

    mov r8, CHAR_H

.y:
    mov r9, CHAR_W

.x:
    mov dword [rdi + r10], 0
    add r10, 4
    dec r9
    jnz .x

    mov eax, [sl]
    shl rax, 2
    add r10, rax
    sub r10, CHAR_W * 4

    dec r8
    jnz .y

    pop rbx
    ret

;================ blink =================

cursor_tick:
    dec qword [cursor_timer]
    jnz .done

    mov qword [cursor_timer], CURSOR_DELAY

    cmp byte [cursor_state], 0
    jne .hide

    call draw_cursor
    mov byte [cursor_state], 1
    ret

.hide:
    call erase_cursor
    mov byte [cursor_state], 0

.done:
    ret

erase_cursor_if_visible:
    cmp byte [cursor_state], 0
    je .done
    call erase_cursor
    mov byte [cursor_state], 0
.done:
    ret

;================ keyboard =================

init_keyboard:
    push rbx
    push r12

    mov r12, rsp
    and rsp, -16
    sub rsp, 32

    mov rcx, [conin]
    test rcx, rcx
    jz .done

    xor edx, edx
    call qword [rcx]

.done:
    mov rsp, r12
    pop r12
    pop rbx
    ret

keyboard_poll:
    push rbx
    push r12

    mov r12, rsp
    and rsp, -16
    sub rsp, 48

    mov rcx, [conin]
    test rcx, rcx
    jz .nokey

    lea rdx, [rsp + 32]
    call qword [rcx + 8]

    test rax, rax
    jnz .nokey

    movzx eax, word [rsp + 34]

    cmp eax, 13
    jne .not_cr
    mov eax, 10
.not_cr:

    cmp eax, 127
    jne .not_del
    mov eax, 8
.not_del:

    cmp eax, 8
    je .key_ok
    cmp eax, 10
    je .key_ok

    cmp eax, 32
    jb .nokey
    cmp eax, 127
    ja .nokey

.key_ok:
    mov rsp, r12
    pop r12
    pop rbx
    ret

.nokey:
    xor eax, eax
    mov rsp, r12
    pop r12
    pop rbx
    ret

;================ char =================

draw_char:
    push rbx
    push rsi
    push r12
    push r13
    push r14

    mov r12, rcx
    mov r13, rdx
    mov r14d, r8d

    movzx eax, r9b

    cmp eax, 32
    jb .empty
    cmp eax, 127
    ja .empty

    sub eax, 32
    shl eax, 3

    lea rsi, [font_table]
    add rsi, rax

    mov rdi, [fb]
    mov ebx, [sl]

    xor r10d, r10d

.row:
    cmp r10d, 8
    je .done

    mov al, [rsi + r10]
    mov r11d, 8

.col:
    test al, 0x80
    jz .skip

    mov rdx, r13
    add rdx, r10
    imul rdx, rbx
    add rdx, r12

    mov rcx, 8
    sub rcx, r11
    add rdx, rcx

    mov dword [rdi + rdx * 4], r14d

.skip:
    shl al, 1
    dec r11d
    jnz .col

    inc r10d
    jmp .row

.empty:
.done:
    pop r14
    pop r13
    pop r12
    pop rsi
    pop rbx
    ret

;================ fail =================

fail:
    mov dx, 0xE9
    mov al, 'F'
    out dx, al

.fail_loop:
    hlt
    jmp .fail_loop

