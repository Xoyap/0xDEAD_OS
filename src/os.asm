    rep stosd
    mov rcx,100
    mov rdx,100
    mov r8d,0x00FFFFFF
    lea r9,[msg]
    call draw_text

hang:
    hlt
    jmp hang

draw_text:
    push r12
    push r13
    push r14
    push r15
    mov r12,rcx
    mov r13,rdx
    mov r14d,r8d
    mov r15,r9

.loop:
    movzx eax,byte [r15]
    test eax,eax
    jz .done
    mov rcx,r12
    mov rdx,r13
    mov r8d,r14d
    mov r9b,al
    call draw_char
    add r12,9
    inc r15
    jmp .loop

.done:
    pop r15
    pop r14
    pop r13
    pop r12
    ret

draw_char:
    push rbx
    push rsi
    push r12
    push r13
    push r14
    mov r12,rcx
    mov r13,rdx
    mov r14d,r8d
    movzx eax,r9b
    cmp eax,32
    jb .empty
    cmp eax,127
    ja .empty
    sub eax,32
    shl eax,3
    lea rsi,[font_table]
    add rsi,rax
    mov rdi,[fb]
    mov ebx,[sl]
    xor r10d,r10d

.row:
    cmp r10d,8
    je .done

    movzx eax,byte [rsi+r10]

    mov r11d,8

.col:
    test al,0x80
    jz .skip_pixel

    mov edx,r13d
    add edx,r10d
    imul edx,ebx
    add edx,r12d

    mov ecx,8
    sub ecx,r11d
    add edx,ecx

    mov dword [rdi+rdx*4],r14d


.skip_pixel:
    shl al,1
    dec r11d
    jnz .col

    inc r10d
    jmp .row


.empty:
    pop r14
    pop r13
    pop r12
    pop rsi
    pop rbx
    ret

.done:
    pop r14
    pop r13
    pop r12
    pop rsi
    pop rbx
    ret

fail:
    mov dx,0xE9
    mov al,'F'
    out dx,al

.fail_loop:
    hlt
    jmp .fail_loop

